"""Built-in /peat research and /peat digest workflows.

These are *prompt builders*, not executors. The CLI receives the prompt
and dispatches it to the live agent (which has the right tools wired in)
exactly the same way ``/replay run`` and ``/qa new`` do. Keeping these
as pure prompt-builders keeps them deterministic and easy to test.
"""

from __future__ import annotations

import json
import logging
import time
from pathlib import Path
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from bog_agents_cli.peat.persona import PeatPersona

logger = logging.getLogger(__name__)


