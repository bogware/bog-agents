# /peat research
# ---------------------------------------------------------------------------


def build_research_prompt(
    persona: PeatPersona,
    *,
    topic: str,
    focus: str = "",
    config_dir: Path,
) -> str:
    """Render a multi-step research prompt for ``topic``.

    The prompt directs the agent through a deliberate plan: scoping →
    search → fetch sources → cross-check → produce a structured report.
    The agent uses whatever search/web/MCP tools it has available; if
    none, it stops and tells the user what to enable.

    Args:
        persona: Resolved persona.
        topic: The thing to research (a product, library, vendor, etc.).
        focus: Optional comma-separated angles to weight (``"security,
            pricing, integrations"``).
        config_dir: User config root — used to compute the report path.

    Returns:
        Prompt for the agent.
    """
    output_dir = config_dir / "peat" / "research"
    output_dir.mkdir(parents=True, exist_ok=True)
    safe_slug = "".join(c for c in topic.lower() if c.isalnum() or c in "-_")[:60] or "topic"
    stamp = time.strftime("%Y%m%d", time.gmtime())
    output_path = output_dir / f"{stamp}-{safe_slug}.md"

    focus_block = ""
    if focus:
        focus_items = [f.strip() for f in focus.split(",") if f.strip()]
        if focus_items:
            focus_block = "\n## Focus angles\n\n" + "\n".join(f"- {f}" for f in focus_items) + "\n"

    return (
        f"{persona.to_system_prompt()}\n"
        "\n## Deep research request\n\n"
        f"Research this topic and produce a structured report:\n\n**{topic}**\n"
        f"{focus_block}\n"
        "Save the final report to:\n\n"
        f"  `{output_path}`\n\n"
        "## Method — follow these phases in order\n\n"
        "**Phase 1: Scope.** Write 3 sub-questions you'll answer to fully address "
        "the topic. State them up front in your scratch work. If the topic is "
        "ambiguous, ask the user *one* clarifying question and stop until they "
        "answer.\n\n"
        "**Phase 2: Search.** Use the web-search tool (or whatever search-capable "
        "MCP tool is configured) to find at least 5 distinct sources. Prefer "
        "primary sources (official docs, vendor pages, RFCs, peer-reviewed "
        "papers) over blog posts. If no search tool is available, stop and tell "
        "the user which one to enable.\n\n"
        "**Phase 3: Fetch & extract.** For each source, fetch the actual page "
        "content (don't rely on snippets), and extract the relevant sections. "
        "Note publication date, author/org, and confidence level (primary vs "
        "secondary).\n\n"
        "**Phase 4: Cross-check.** Identify points where sources disagree. Call "
        "those out explicitly in the report — do not silently pick a winner.\n\n"
        "**Phase 5: Write the report.** Use this exact structure:\n\n"
        "    # <topic>\n\n"
        "    *Generated by Peat on <date>.*\n\n"
        "    ## TL;DR\n\n"
        "    <3-5 bullet points the user can scan in 30 seconds.>\n\n"
        "    ## Key findings\n\n"
        "    <one section per sub-question. Include specifics, not platitudes.>\n\n"
        "    ## Where sources disagree\n\n"
        "    <bulleted list of disagreements with one-line context each.>\n\n"
        "    ## Open questions\n\n"
        "    <things you couldn't resolve, with what would resolve them.>\n\n"
        "    ## Sources\n\n"
        "    <numbered list. for each: title, URL, date, primary/secondary, "
        "    1-line takeaway.>\n\n"
        f"    {persona.sign_off}\n\n"
        "## Honesty rules\n\n"
        "- If a source contradicts something you 'know' from training, prefer "
        "the source. Note the discrepancy in 'Where sources disagree'.\n"
        "- If you couldn't find good evidence for a claim, say so — never invent.\n"
        "- If a search returned zero useful results, say so plainly. Don't pad.\n"
    )


