"""Theme registry: built-in Textual themes plus user-defined themes.

Textual resolves colors from the *active theme* (`App.theme`). Historically
the CLI shipped no registered theme and instead hard-coded the matte-swamp
palette as `$primary: …` overrides at the top of `app.tcss`. Those CSS-level
overrides shadowed whatever theme was active, which is why a `/theme` command
could never actually change anything.

This module makes the palette a real, registered Textual `Theme` named
`bog` and sets it as the default, so the `app.tcss` override block can be
removed while leaving the default look **byte-identical**. Every variable the
app's CSS references (`$primary`, `$surface`, `$highlight`, `$boundary`,
`$text`, `$accent`, …) resolves to the exact same hex it did before — the
lighten/darken/highlight/boundary/text variants that Textual would otherwise
*derive* are pinned in the theme's `variables` dict so no rounding or hue
drift can creep in. See `tests/unit_tests/test_theme.py`.

Extra built-in themes (`bog-light`, `abyss`, `ember`) and user themes give
`/theme` something to switch between. Users add themes under `[themes.<name>]`
in `~/.bog-agents/config.toml`; see `load_user_theme_specs()`.

Three CSS variables — `highlight`, `highlight-soft`, and `boundary` — are
app-specific and are *not* generated by Textual's color system, so every
registered theme must supply them (via `variables`) or the referencing CSS
rules would fail to resolve. Built-in specs always carry them; user themes
fall back to the base palette's values when omitted.
"""

from __future__ import annotations

import logging
import re
from dataclasses import dataclass, field
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from collections.abc import Iterable, Mapping

    from textual.app import App
    from textual.theme import Theme

logger = logging.getLogger(__name__)

DEFAULT_THEME_NAME = "bog"
"""Theme applied on startup when the user has saved no preference."""

_HEX_RE = re.compile(r"^#(?:[0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})$")
"""Matches a 7- or 9-char hex color (`#RRGGBB` / `#RRGGBBAA`).

Textual's `Color.parse` would also validate, but a local regex keeps the
registry importable on the `bog-agents --help` cold path without importing
Textual (~0.5s).
"""

# App-specific CSS variables Textual does NOT generate. Every theme must
# provide these three or CSS that references `$highlight` / `$highlight-soft`
# / `$boundary` (e.g. the input divider, hover veils) fails to resolve.
_REQUIRED_CUSTOM_VARS = ("highlight", "highlight-soft", "boundary")

# CSS variables a user theme may pin directly (beyond the base Theme fields).
# Anything not listed here is either a base field or left for Textual to
# derive from the base fields.
_PINNABLE_VARS = (
    "primary-lighten-1",
    "primary-lighten-2",
    "primary-darken-1",
    "primary-darken-2",
    "surface-lighten-1",
    "surface-darken-1",
    "highlight",
    "highlight-soft",
    "boundary",
    "text",
    "text-muted",
    "warning",
)


@dataclass(frozen=True, slots=True)
class ThemeSpec:
    """A theme as a set of base colors plus pinned CSS-variable overrides.

    The base fields map straight onto Textual's `Theme` fields. `variables`
    pins the derived / app-specific variables that must not be left to
    Textual's derivation (either to stay byte-identical with the old palette,
    or because Textual does not generate them at all — see
    `_REQUIRED_CUSTOM_VARS`).
    """

    name: str
    """Registry key and `App.theme` value (e.g. `'bog'`)."""

    label: str
    """Human-readable name shown in the picker (e.g. `'Bog (peat)'`)."""

    dark: bool
    """Whether this is a dark theme variant."""

    primary: str
    secondary: str
    background: str
    surface: str
    foreground: str
    success: str
    warning: str
    error: str
    accent: str

    variables: Mapping[str, str] = field(default_factory=dict)
    """Pinned CSS variables merged over Textual's generated set."""

    def __post_init__(self) -> None:
        """Validate every color is hex and required custom vars are present.

        Raises:
            ValueError: If any base color is not a hex string, if any pinned
                variable value is not a hex string, or if a required custom
                variable (`highlight` / `highlight-soft` / `boundary`) is
                missing.
        """
        for attr in (
            "primary",
            "secondary",
            "background",
            "surface",
            "foreground",
            "success",
            "warning",
            "error",
            "accent",
        ):
            val = getattr(self, attr)
            if not _HEX_RE.match(val):
                msg = f"ThemeSpec.{attr} must be a hex color, got {val!r}"
                raise ValueError(msg)
        for key, val in self.variables.items():
            if not _HEX_RE.match(val):
                msg = f"ThemeSpec.variables[{key!r}] must be a hex color, got {val!r}"
                raise ValueError(msg)
        missing = [v for v in _REQUIRED_CUSTOM_VARS if v not in self.variables]
        if missing:
            msg = f"ThemeSpec {self.name!r} missing required variables: {missing}"
            raise ValueError(msg)

    def to_theme(self) -> Theme:
        """Build the Textual `Theme` this spec describes.

        Returns:
            A `textual.theme.Theme` carrying the base colors and the pinned
            `variables`.
        """
        from textual.theme import Theme

        return Theme(
            name=self.name,
            primary=self.primary,
            secondary=self.secondary,
            warning=self.warning,
            error=self.error,
            success=self.success,
            accent=self.accent,
            foreground=self.foreground,
            background=self.background,
            surface=self.surface,
            dark=self.dark,
            variables=dict(self.variables),
        )


