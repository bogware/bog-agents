def _spec_from_section(name: str, section: Mapping[str, Any]) -> ThemeSpec | None:
    """Build a `ThemeSpec` from one `[themes.<name>]` config section.

    Unrecognized or malformed fields are logged and ignored; a section that
    cannot yield a valid spec (missing `label`, all-invalid colors) returns
    `None` rather than raising, so one bad user theme never blocks startup.

    Missing base colors fall back to the `bog` (dark) or `bog-light` (light)
    palette. Missing `highlight` / `highlight-soft` / `boundary` fall back to
    the same base so the required custom variables are always present.

    Args:
        name: The theme name (the `<name>` in `[themes.<name>]`).
        section: The parsed TOML table for this theme.

    Returns:
        A validated `ThemeSpec`, or `None` when the section is unusable.
    """
    label = section.get("label")
    if not isinstance(label, str) or not label.strip():
        logger.warning("User theme %r missing required 'label' (str); skipping", name)
        return None

    dark_raw = section.get("dark", True)
    if not isinstance(dark_raw, bool):
        logger.warning(
            "User theme %r: 'dark' must be true/false, got %r; defaulting to dark",
            name,
            dark_raw,
        )
        dark_raw = True

    base = BOG_SPEC if dark_raw else BOG_LIGHT_SPEC

    def _color(key: str, fallback: str) -> str:
        raw = section.get(key)
        if isinstance(raw, str) and _HEX_RE.match(raw):
            return raw
        if raw is not None:
            logger.warning(
                "User theme %r field %r is not a hex color (%r); using fallback",
                name,
                key,
                raw,
            )
        return fallback

    variables: dict[str, str] = {}
    for key in _PINNABLE_VARS:
        raw = section.get(key)
        if isinstance(raw, str) and _HEX_RE.match(raw):
            variables[key] = raw
        elif raw is not None:
            logger.warning(
                "User theme %r variable %r is not a hex color (%r); ignoring",
                name,
                key,
                raw,
            )
    # Guarantee the required custom vars exist by falling back to the base.
    for key in _REQUIRED_CUSTOM_VARS:
        variables.setdefault(key, base.variables[key])

    try:
        return ThemeSpec(
            name=name,
            label=label,
            dark=dark_raw,
            primary=_color("primary", base.primary),
            secondary=_color("secondary", base.secondary),
            background=_color("background", base.background),
            surface=_color("surface", base.surface),
            foreground=_color("foreground", base.foreground),
            success=_color("success", base.success),
            warning=_color("warning", base.warning),
            error=_color("error", base.error),
            accent=_color("accent", base.accent),
            variables=variables,
        )
    except ValueError:
        logger.warning("User theme %r is invalid; skipping", name, exc_info=True)
        return None


def load_user_theme_specs(
    config: Mapping[str, Any] | None = None,
) -> list[ThemeSpec]:
    """Load user-defined themes from `[themes.<name>]` config sections.

    A user section whose name matches a built-in theme is ignored (built-ins
    are authoritative); use a distinct name to add a theme.

    Args:
        config: Parsed `config.toml` mapping. When `None`, the user's
            `~/.bog-agents/config.toml` is read via
            `config_manifest.load_config_toml`.

    Returns:
        Validated user `ThemeSpec` instances (order follows the config file).
        Invalid sections are logged and skipped.
    """
    if config is None:
        try:
            from bog_agents_cli.config_manifest import load_config_toml

            config = load_config_toml()
        except Exception:
            logger.debug("Could not load config for user themes", exc_info=True)
            return []

    section = config.get("themes")
    if not isinstance(section, dict) or not section:
        return []

    builtin_names = {spec.name for spec in _BUILTIN_SPECS}
    specs: list[ThemeSpec] = []
    for name, table in section.items():
        if name in builtin_names:
            logger.warning(
                "User theme %r shadows a built-in theme name; ignoring", name
            )
            continue
        if not isinstance(table, dict):
            logger.warning("Ignoring non-table [themes.%s]", name)
            continue
        spec = _spec_from_section(name, table)
        if spec is not None:
            specs.append(spec)
    return specs


def all_theme_specs(config: Mapping[str, Any] | None = None) -> list[ThemeSpec]:
    """Return built-in specs followed by valid user specs.

    Args:
        config: Optional parsed config (see `load_user_theme_specs`).

    Returns:
        Built-in then user `ThemeSpec` instances.
    """
    return [*_BUILTIN_SPECS, *load_user_theme_specs(config)]


def theme_labels(config: Mapping[str, Any] | None = None) -> dict[str, str]:
    """Return an ordered `{name: label}` map of every available theme.

    Args:
        config: Optional parsed config (see `load_user_theme_specs`).

    Returns:
        Insertion-ordered mapping from theme name to its display label.
    """
    return {spec.name: spec.label for spec in all_theme_specs(config)}


def register_all_themes(
    app: App,
    *,
    config: Mapping[str, Any] | None = None,
) -> list[str]:
    """Register every built-in and user theme with the Textual app.

    Safe to call once during `on_mount`. Registration failures for a single
    theme are logged and skipped so one bad user theme cannot break startup.

    Args:
        app: The Textual application to register themes on.
        config: Optional parsed config (see `load_user_theme_specs`).

    Returns:
        The names of the themes successfully registered, in order.
    """
    registered: list[str] = []
    for spec in all_theme_specs(config):
        try:
            app.register_theme(spec.to_theme())
        except Exception:
            logger.warning("Could not register theme %r", spec.name, exc_info=True)
            continue
        registered.append(spec.name)
    return registered


def resolve_theme_name(
    requested: str,
    *,
    config: Mapping[str, Any] | None = None,
) -> str | None:
    """Return the exact theme name matching `requested`, or `None`.

    Matches case-insensitively against theme names so `/theme BOG` works.

    Args:
        requested: The user-supplied theme name.
        config: Optional parsed config (see `load_user_theme_specs`).

    Returns:
        The canonical theme name if found, otherwise `None`.
    """
    wanted = requested.strip().lower()
    for spec in all_theme_specs(config):
        if spec.name.lower() == wanted:
            return spec.name
    return None


@dataclass(frozen=True, slots=True)
class ThemeCommandResult:
    """Outcome of a non-interactive `/theme` invocation.

    Attributes:
        message: Text to show the user.
        apply: Theme name to switch to and persist, or `None` for list /
            error results where no switch should happen.
        is_error: Whether `message` describes a failure.
    """

    message: str
    apply: str | None = None
    is_error: bool = False


def handle_theme_command(
    arg: str,
    *,
    current: str | None = None,
    config: Mapping[str, Any] | None = None,
) -> ThemeCommandResult:
    """Pure controller for `/theme <arg>` (no TUI dependencies).

    `arg` is the text after `/theme`. `''` is handled by the caller (opens
    the picker) and should not reach here; if it does it is treated as
    `list`. `list` returns the catalog; anything else is treated as a theme
    name to switch to.

    Args:
        arg: The argument text after `/theme` (already stripped).
        current: The currently active theme name, marked in `list` output.
        config: Optional parsed config (see `load_user_theme_specs`).

    Returns:
        A `ThemeCommandResult` describing the message and whether to apply a
        theme.
    """
    normalized = arg.strip()
    if not normalized or normalized.lower() == "list":
        return ThemeCommandResult(message=_format_theme_list(current, config))

    resolved = resolve_theme_name(normalized, config=config)
    if resolved is None:
        names = ", ".join(theme_labels(config))
        return ThemeCommandResult(
            message=f"Unknown theme {normalized!r}. Available: {names}",
            is_error=True,
        )

    label = theme_labels(config).get(resolved, resolved)
    return ThemeCommandResult(
        message=f"Theme set to {label} ({resolved}).",
        apply=resolved,
    )


def _format_theme_list(
    current: str | None,
    config: Mapping[str, Any] | None,
) -> str:
    """Format the `/theme list` output.

    Args:
        current: The active theme name (marked with a bullet).
        config: Optional parsed config (see `load_user_theme_specs`).

    Returns:
        A multi-line string listing each theme's name and label.
    """
    lines = ["Available themes:"]
    for spec in all_theme_specs(config):
        marker = "*" if spec.name == current else " "
        variant = "dark" if spec.dark else "light"
        lines.append(f"  {marker} {spec.name} — {spec.label} ({variant})")
    lines.append("Use /theme <name> to switch, or /theme to open the picker.")
    return "\n".join(lines)


def theme_names(config: Mapping[str, Any] | None = None) -> Iterable[str]:
    """Yield every available theme name, built-ins first.

    Args:
        config: Optional parsed config (see `load_user_theme_specs`).

    Yields:
        Theme names in registration order.
    """
    for spec in all_theme_specs(config):
        yield spec.name
